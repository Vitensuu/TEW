namespace Dungeon
{
    /// <summary>
    /// Тип стенового тайла определяемый по соседям в DungeonGrid.
    /// Каждая позиция стены может потребовать до 2 тайлов по вертикали
    /// (верхний и нижний слои рисуются на разных Tilemap-слоях).
    /// </summary>
    public enum WallCellType
    {
        None,

        // ── ТИП 1 (снаружи) ──────────────────────
        // Верхняя граница комнаты — игрок видит лицевую стену снизу

        T1_CornerTopLeft,       // верхний левый угол коробки
        T1_CornerTopRight,      // верхний правый угол коробки
        T1_WallTop,             // верхняя стена (горизонталь)
        T1_WallLeft,            // левая боковая стена коробки
        T1_WallRight,           // правая боковая стена коробки
        T1_CornerFaceLeft,      // левый угол лицевой стены (нижний левый угол коробки снаружи)
        T1_CornerFaceRight,     // правый угол лицевой стены (нижний правый угол коробки снаружи)
        T1_WallFace,            // лицевая стена (нижняя горизонталь коробки снаружи)

        // ── ТИП 2 (изнутри) ──────────────────────
        // Нижняя граница комнаты — игрок внутри видит заднюю стенку

        T2_CornerTopLeft,       // верхний левый угол изнутри
        T2_CornerTopRight,      // верхний правый угол изнутри
        T2_WallTop,             // верхняя стена изнутри (задняя)
        T2_WallLeft,            // левая боковая изнутри
        T2_WallRight,           // правая боковая изнутри
        T2_CornerBotLeft,       // нижний левый угол изнутри
        T2_CornerBotRight,      // нижний правый угол изнутри
        T2_WallBot,             // нижняя стена изнутри (1 тайл)
    }
}
