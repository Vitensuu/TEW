namespace Game.Dungeon
{
    /// <summary>
    /// Роль готовой комнаты-префаба в собранном этаже.
    /// Дизайнер помечает каждый Room Prefab одним из этих типов в RoomData.
    /// (Новая архитектура: комнаты НЕ генерируются процедурно — только собираются.)
    /// </summary>
    public enum RoomType
    {
        Start,     // вход игрока (ровно одна на этаж)
        Normal,    // обычная боевая комната
        Elite,     // усиленные враги
        Treasure,  // сокровищница
        Shop,      // магазин
        Event,     // событие/выбор
        Shrine,    // святилище (баффы)
        Boss,      // комната босса
        Secret,    // секретная комната
        Exit       // выход на следующий этаж (ровно одна)
    }
}
