namespace Dungeon.Procedural
{
    /// <summary>
    /// Роль комнаты в подземелье. Старт и Босс ставятся ровно один раз
    /// (старт — первая комната, босс — самая дальняя по графу). Остальные
    /// раздаются по весам. Расширяется свободно — добавь значение и вес
    /// в DungeonGenerator.RollType().
    /// </summary>
    public enum RoomType
    {
        Start,     // стартовая комната игрока (ровно одна)
        Normal,    // обычная боевая комната
        Treasure,  // сокровищница (лут)
        Shop,      // магазин
        Elite,     // элитные враги
        Boss       // комната босса (ровно одна, самая дальняя)
    }
}
